/// Run `gen-layer-catalogs [--check|--write]`.
///
/// Writing is the default. `--check` compares every committed artifact
/// byte-for-byte against the generator output and fails on the first
/// difference, and either way the returned paths name what was written or
/// checked, so a caller cannot read silence as currency.
pub fn run_cli(repo_root: &std::path::Path, args: &[String]) -> Result<Vec<PathBuf>, String> {
    let check = match args {
        [] => false,
        [flag] if flag == "--check" => true,
        [flag] if flag == "--write" => false,
        _ => {
            return Err(
                "usage: cargo run -p xtask -- gen-layer-catalogs [--check|--write]".to_owned(),
            );
        }
    };
    let mut written = Vec::new();
    for (relative, content) in artifacts() {
        let path = repo_root.join(&relative);
        if check {
            let committed = fs::read_to_string(&path).map_err(|error| {
                format!(
                    "{}: unreadable generated artifact: {error}",
                    relative.display()
                )
            })?;
            if committed != content {
                return Err(format!(
                    "{}: committed artifact differs from the generator output",
                    relative.display()
                ));
            }
        } else {
            if let Some(parent) = path.parent() {
                fs::create_dir_all(parent)
                    .map_err(|error| format!("{}: {error}", relative.display()))?;
            }
            fs::write(&path, content)
                .map_err(|error| format!("{}: {error}", relative.display()))?;
        }
        written.push(path);
    }
    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The audit vocabulary carries the whole registry: a converted type the
    /// record classes can address is never missing from the list.
    #[test]
    fn audit_vocabulary_covers_the_registry() {
        let types = audit_resource_types();
        for resource_type in V3_CONVERTED_RESOURCE_TYPES {
            assert!(types.iter().any(|value| value == resource_type));
        }
        assert!(types.iter().any(|value| value == VENDOR_TYPE));
        assert_eq!(types.len(), V3_CONVERTED_RESOURCE_TYPES.len() + 1);
    }

    /// The metric label domain carries the whole standard registry.
    #[test]
    fn metric_vocabulary_covers_the_standard_registry() {
        let types = metric_resource_types();
        for resource_type in STANDARD_RESOURCE_TYPES {
            assert!(types.iter().any(|value| value == resource_type));
        }
        assert_eq!(types.len(), STANDARD_RESOURCE_TYPES.len() + 1);
    }

    /// The mutation verbs are the Role resource verbs minus the read-only
    /// three, so neither list can grow a verb the contract does not declare.
    #[test]
    fn mutation_verbs_are_the_role_verbs_minus_the_read_only_three() {
        let mutating = resource_mutation_verbs();
        assert_eq!(mutating.len(), RoleResourceVerb::ALL.len() - 3);
        for spelling in resource_verbs() {
            let read_only = READ_ONLY_VERBS
                .iter()
                .map(verb_spelling)
                .any(|verb| verb == spelling);
            assert_eq!(mutating.contains(&spelling), !read_only, "{spelling}");
        }
    }

    /// The typed surface entries name declared resource types.
    #[test]
    fn typed_surface_entries_name_declared_types() {
        for (noun, resource_type) in TYPED_NOUNS.iter().chain(TYPED_VERB_TYPES) {
            assert!(
                V3_CONVERTED_RESOURCE_TYPES.contains(resource_type),
                "{noun}: {resource_type} is not a converted resource type"
            );
        }
        assert!(!UNSAFE_LOCAL_PROVIDER_REF.is_empty());
        assert!(!UNSAFE_LOCAL_PROVIDER_KIND.is_empty());
        assert!(!CONTROLLER_OWNED_TYPES.is_empty());
        assert!(!NO_ISOLATION_TARGET_TYPES.is_empty());
        assert!(!EXECUTION_TARGET_TYPES.is_empty());
        assert!(!NO_ISOLATION_POSTURES.is_empty());
    }

    /// The process provider vocabulary projects both consumer domains.
    #[test]
    fn process_provider_domains_project_from_one_vocabulary() {
        assert_eq!(process_provider_ids(None).len(), PROCESS_PROVIDERS.len());
        assert_eq!(
            process_provider_ids(Some(true)),
            vec!["minijail".to_owned(), "systemd".to_owned()]
        );
    }
}
