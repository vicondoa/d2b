//! The client-layer catalog generator.
//!
//! `gen-layer-catalogs` projects the declared resource-plane vocabulary into
//! the crate-local views the client-facing layers consume, so no layer keeps
//! a hand copy of a list the declaration already owns:
//!
//! - `packages/d2b/src/generated/surface_catalog.rs` - the CLI's resource
//!   type registry, its typed nouns, its typed-verb gates, the execution
//!   targets, the controller-owned types, and the no-isolation vocabulary.
//! - `packages/d2b-audit/src/generated/audit_catalog.rs` - the audit record
//!   type vocabulary, the resource mutation verbs, and the process-provider
//!   vocabulary.
//! - `packages/d2b-contracts-provider/src/v3/generated/telemetry_catalog.rs` -
//!   the metric label resource-type and verb domains and the process-provider
//!   label domain.
//!
//! Every list is either projected from a committed authority (the standard
//! and converted resource type registries in `d2b-contracts`, the Role
//! resource verbs in `d2b-contracts-zone-session`) or declared by one table
//! here. Nothing is restated beside a generated copy, and each emitted file
//! is compared byte-for-byte against this generator by its drift target.

use std::{fmt::Write as _, fs, path::PathBuf};

use d2b_contracts::identity::{STANDARD_RESOURCE_TYPES, V3_CONVERTED_RESOURCE_TYPES};
use d2b_contracts_zone_session::v3::RoleResourceVerb;

/// The CLI's generated directory.
const CLI_OUT_DIR: &str = "packages/d2b/src/generated";
/// The audit crate's generated directory.
const AUDIT_OUT_DIR: &str = "packages/d2b-audit/src/generated";
/// The provider contracts crate's generated directory.
const TELEMETRY_OUT_DIR: &str = "packages/d2b-contracts-provider/src/v3/generated";

/// The generated module file every directory carries.
const MOD_FILE: &str = "mod.rs";

/// The shared byte-exact header every generated artifact carries.
const HEADER: &str = concat!(
    "// @generated by `cargo run -p xtask -- gen-layer-catalogs`.\n",
    "// Do not hand-edit: the generator's `--check` form compares this file\n",
    "// byte-for-byte against its output.\n",
);

/// The pseudo type name the audit and metric vocabularies admit for resources
/// whose type is outside the registry.
const VENDOR_TYPE: &str = "vendor";

/// The resource verb spellings that only read.
const READ_ONLY_VERBS: [RoleResourceVerb; 3] = [
    RoleResourceVerb::Get,
    RoleResourceVerb::List,
    RoleResourceVerb::Watch,
];

/// One process provider the layer vocabularies admit.
struct ProcessProvider {
    /// The label value the process surfaces carry.
    id: &'static str,
    /// Whether the process metric label domain admits the id.
    metric_label: bool,
}

/// The process-provider vocabulary.
///
/// The audit class admits every entry; the process metric families label the
/// subset their emitters serve. No crate keeps a second copy of either list.
const PROCESS_PROVIDERS: &[ProcessProvider] = &[
    ProcessProvider {
        id: "minijail",
        metric_label: true,
    },
    ProcessProvider {
        id: "systemd",
        metric_label: true,
    },
    ProcessProvider {
        id: "system-core-user",
        metric_label: false,
    },
];

/// The typed nouns and the resource type each addresses.
const TYPED_NOUNS: &[(&str, &str)] = &[
    ("volume", "Volume"),
    ("network", "Network"),
    ("device", "Device"),
    ("user", "User"),
    ("credential", "Credential"),
    ("quota", "Quota"),
    ("emergency-policy", "EmergencyPolicy"),
    ("guest", "Guest"),
    ("process", "Process"),
];

/// The typed verbs and the resource type each is available on.
const TYPED_VERB_TYPES: &[(&str, &str)] = &[
    ("verify", "Volume"),
    ("usb", "Device"),
    ("security-key", "Device"),
];

/// The resource types the controller owns: no operator authors one.
const CONTROLLER_OWNED_TYPES: &[&str] = &["Endpoint"];

/// The resource types that serve as an execution target.
const EXECUTION_TARGET_TYPES: &[&str] = &["Host", "Guest"];

/// The provider reference of a workload running without an isolation
/// boundary.
const UNSAFE_LOCAL_PROVIDER_REF: &str = "Provider/unsafe-local";

/// The provider kind a no-isolation row carries.
const UNSAFE_LOCAL_PROVIDER_KIND: &str = "unsafe-local";

/// The postures that mean the row has no isolation boundary.
const NO_ISOLATION_POSTURES: &[&str] = &["none", "unsafe-local"];

/// The execution targets that run without an isolation boundary.
const NO_ISOLATION_TARGET_TYPES: &[&str] = &["Host"];

/// Render the doc-comment lines of one generated item.
fn doc_lines(lines: &[&str]) -> String {
    let mut out = String::new();
    for line in lines {
        if line.is_empty() {
            out.push_str("///\n");
        } else {
            let _ = writeln!(out, "/// {line}");
        }
    }
    out
}

/// Render one `&[&str]` constant.
fn string_slice(name: &str, doc: &[&str], values: &[String]) -> String {
    let mut out = doc_lines(doc);
    let _ = write!(out, "pub const {name}: &[&str] = &[\n");
    for value in values {
        let _ = write!(out, "    \"{value}\",\n");
    }
    out.push_str("];\n");
    out
}

/// Render one closed `&[&str]` constant.
fn string_array(name: &str, doc: &[&str], values: &[String]) -> String {
    let mut out = doc_lines(doc);
    let _ = write!(out, "pub const {name}: &[&str] = &[\n");
    for value in values {
        let _ = write!(out, "    \"{value}\",\n");
    }
    out.push_str("];\n");
    out
}

/// Render one `&[(&str, &str)]` constant.
fn string_pair_slice(name: &str, doc: &[&str], values: &[(&str, &str)]) -> String {
    let mut out = doc_lines(doc);
    let _ = write!(out, "pub const {name}: &[(&str, &str)] = &[\n");
    for (left, right) in values {
        let _ = write!(out, "    (\"{left}\", \"{right}\"),\n");
    }
    out.push_str("];\n");
    out
}

/// The kebab-case spelling of one role vocabulary entry.
fn verb_spelling(verb: &RoleResourceVerb) -> String {
    serde_json::to_value(verb)
        .expect("a contract verb serializes")
        .as_str()
        .expect("a contract verb is a string")
        .to_owned()
}

/// Every resource verb, in contract order.
fn resource_verbs() -> Vec<String> {
    RoleResourceVerb::ALL.iter().map(verb_spelling).collect()
}

/// The resource verbs that mutate, in contract order.
fn resource_mutation_verbs() -> Vec<String> {
    RoleResourceVerb::ALL
        .iter()
        .filter(|verb| !READ_ONLY_VERBS.contains(verb))
        .map(verb_spelling)
        .collect()
}

/// The audit record type vocabulary: the converted registry, then the vendor
/// pseudo type.
fn audit_resource_types() -> Vec<String> {
    let mut values = V3_CONVERTED_RESOURCE_TYPES
        .iter()
        .map(|value| (*value).to_owned())
        .collect::<Vec<_>>();
    values.push(VENDOR_TYPE.to_owned());
    values
}

/// The metric label resource type domain: the standard registry, then the
/// vendor pseudo type.
fn metric_resource_types() -> Vec<String> {
    let mut values = STANDARD_RESOURCE_TYPES
        .iter()
        .map(|value| (*value).to_owned())
        .collect::<Vec<_>>();
    values.push(VENDOR_TYPE.to_owned());
    values
}

/// The process-provider ids one consumer admits.
fn process_provider_ids(metric_label: Option<bool>) -> Vec<String> {
    PROCESS_PROVIDERS
        .iter()
        .filter(|provider| metric_label.is_none_or(|metric| provider.metric_label == metric))
        .map(|provider| provider.id.to_owned())
        .collect()
}

/// Render the CLI's surface catalog module.
fn surface_catalog_source() -> String {
    let mut source = String::from(HEADER);
    source.push_str(&string_array(
        "RESOURCE_TYPES",
        &[
            "The resource types the CLI addresses, in registry order.",
            "",
            "The source of record is `V3_CONVERTED_RESOURCE_TYPES` in",
            "`d2b-contracts`, which the CLI does not link directly; the",
            "generator projects it entry for entry.",
        ],
        &V3_CONVERTED_RESOURCE_TYPES
            .iter()
            .map(|value| (*value).to_owned())
            .collect::<Vec<_>>(),
    ));
    source.push_str(&string_pair_slice(
        "TYPED_NOUNS",
        &["The typed nouns and the resource type each addresses."],
        TYPED_NOUNS,
    ));
    source.push_str(&string_pair_slice(
        "TYPED_VERB_TYPES",
        &["The typed verbs and the resource type each is available on."],
        TYPED_VERB_TYPES,
    ));
    source.push_str(&string_slice(
        "CONTROLLER_OWNED_TYPES",
        &["The resource types the controller owns: no operator authors one."],
        &CONTROLLER_OWNED_TYPES
            .iter()
            .map(|value| (*value).to_owned())
            .collect::<Vec<_>>(),
    ));
    source.push_str(&string_slice(
        "EXECUTION_TARGET_TYPES",
        &["The resource types that serve as an execution target."],
        &EXECUTION_TARGET_TYPES
            .iter()
            .map(|value| (*value).to_owned())
            .collect::<Vec<_>>(),
    ));
    source.push_str(&doc_lines(&[
        "The provider reference of a workload running without an isolation",
        "boundary.",
    ]));
    let _ = writeln!(
        source,
        "pub const UNSAFE_LOCAL_PROVIDER_REF: &str = \"{UNSAFE_LOCAL_PROVIDER_REF}\";"
    );
    source.push_str(&doc_lines(&[
        "The provider kind a no-isolation row carries.",
    ]));
    let _ = writeln!(
        source,
        "pub const UNSAFE_LOCAL_PROVIDER_KIND: &str = \"{UNSAFE_LOCAL_PROVIDER_KIND}\";"
    );
    source.push_str(&string_slice(
        "NO_ISOLATION_POSTURES",
        &["The postures that mean the row has no isolation boundary."],
        &NO_ISOLATION_POSTURES
            .iter()
            .map(|value| (*value).to_owned())
            .collect::<Vec<_>>(),
    ));
    source.push_str(&string_array(
        "MUTATION_VERBS",
        &["The resource verbs that write an audit row, in contract order."],
        &resource_mutation_verbs(),
    ));
    source.push_str(&string_array(
        "PROCESS_PROVIDERS",
        &["The process providers an audit record may name."],
        &process_provider_ids(None),
    ));
    source.push_str(&doc_lines(&[
        "The resource type a typed noun addresses.",
    ]));
    source.push_str(
        "pub fn typed_noun_type(noun: &str) -> Option<&'static str> {\n    \
         TYPED_NOUNS\n        .iter()\n        \
         .find_map(|(name, resource_type)| (*name == noun).then_some(*resource_type))\n}\n",
    );
    source.push_str(&doc_lines(&[
        "The resource type a typed verb is available on.",
    ]));
    source.push_str(
        "pub fn typed_verb_type(verb: &str) -> Option<&'static str> {\n    \
         TYPED_VERB_TYPES\n        .iter()\n        \
         .find_map(|(name, resource_type)| (*name == verb).then_some(*resource_type))\n}\n",
    );
    source.push_str(&doc_lines(&[
        "Whether the resource type is in the registry.",
    ]));
    source.push_str(
        "pub fn admits_resource_type(resource_type: &str) -> bool {\n    \
         RESOURCE_TYPES.contains(&resource_type)\n}\n",
    );
    source.push_str(&doc_lines(&["Whether the verb writes a resource row."]));
    source.push_str(
        "pub fn admits_mutation_verb(verb: &str) -> bool {\n    \
         MUTATION_VERBS.contains(&verb)\n}\n",
    );
    source.push_str(&doc_lines(&[
        "Whether the resource type is one the controller owns.",
    ]));
    source.push_str(
        "pub fn is_controller_owned(resource_type: &str) -> bool {\n    \
         CONTROLLER_OWNED_TYPES.contains(&resource_type)\n}\n",
    );
    source.push_str(&doc_lines(&[
        "Whether the resource type serves as an execution target.",
    ]));
    source.push_str(
        "pub fn is_execution_target(resource_type: &str) -> bool {\n    \
         EXECUTION_TARGET_TYPES.contains(&resource_type)\n}\n",
    );
    source.push_str(&doc_lines(&[
        "Whether the posture marks a row with no isolation boundary.",
    ]));
    source.push_str(
        "pub fn is_no_isolation_posture(posture: &str) -> bool {\n    \
         NO_ISOLATION_POSTURES.contains(&posture)\n}\n",
    );
    source.push_str(&doc_lines(&[
        "Whether the provider reference marks a no-isolation row.",
    ]));
    source.push_str(
        "pub fn is_unsafe_local_provider(reference: &str) -> bool {\n    \
         reference == UNSAFE_LOCAL_PROVIDER_REF\n}\n",
    );
    source.push_str(&doc_lines(&[
        "Whether the provider kind marks a no-isolation row.",
    ]));
    source.push_str(
        "pub fn is_unsafe_local_provider_kind(kind: &str) -> bool {\n    \
         kind == UNSAFE_LOCAL_PROVIDER_KIND\n}\n",
    );
    source.push_str(&string_slice(
        "NO_ISOLATION_TARGET_TYPES",
        &["The execution targets that run without an isolation boundary."],
        &NO_ISOLATION_TARGET_TYPES
            .iter()
            .map(|value| (*value).to_owned())
            .collect::<Vec<_>>(),
    ));
    source.push_str(&doc_lines(&[
        "Whether the execution target runs without an isolation boundary.",
    ]));
    source.push_str(
        "pub fn is_no_isolation_target(resource_type: &str) -> bool {\n    \
         NO_ISOLATION_TARGET_TYPES.contains(&resource_type)\n}\n",
    );
    source
}

