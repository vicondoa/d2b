//! The Nix closed-inventory generator.
//!
//! `gen-nix-inventories` emits the Nix modules whose contents are closed
//! inventories - lists a consumer must not restate:
//!
//! - `nixos-modules/generated/provider-projections.nix` - the Provider
//!   identities that publish a Nix resource projection, in the order the
//!   compiler folds them, and the `d2b._resourceCompiler` option key each
//!   projection lands on.
//! - `nixos-modules/generated/resource-inventories.nix` - the zone-control
//!   type set, the Role/RoleBinding vocabularies, the shared resource-envelope
//!   field vocabularies, the committed schema pointers, and the qualified
//!   types the compiler schema farm carries beyond the standard and semantic
//!   registries.
//! - `nixos-modules/host-users.nix` - the host accounts the committed
//!   principal allocation names.
//! - `nixos-modules/generated/process-role-providers.nix` and
//!   `packages/d2b-core/src/generated/process_roles.rs` - the process
//!   family's declared role-to-provider map and `ProcessRole` vocabulary
//!   (U4), rendered from the per-crate `resource-types.json` declarations by
//!   the resource-type authority and emitted here too so the standalone
//!   command and the layout check stay byte-identical.
//!
//! Every list is either projected from a committed authority (the standard
//! resource registry in `d2b-contracts`, the Role/RoleBinding contracts, the
//! Provider matrix, the committed schema artifacts, the principal
//! allocation) or declared by one table here. Nothing is restated in Nix
//! beside a generated copy, and each emitted file is compared byte-for-byte
//! against this generator by its drift target.

