fn render_error(message: impl Into<String>) -> Box<dyn std::error::Error> {
    message.into().into()
}

/// A Nix double-quoted string.
fn nix_string(value: &str) -> String {
    let mut out = String::with_capacity(value.len() + 2);
    out.push('"');
    for character in value.chars() {
        match character {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '$' => out.push_str("\\$"),
            _ => out.push(character),
        }
    }
    out.push('"');
    out
}

/// A Nix list of strings, one entry per line.
fn nix_string_list<'a>(values: impl IntoIterator<Item = &'a str>, indent: usize) -> String {
    let padding = " ".repeat(indent);
    let mut out = String::from("[\n");
    for value in values {
        out.push_str(&format!("{padding}  {}\n", nix_string(value)));
    }
    out.push_str(&format!("{padding}]"));
    out
}

/// The camel-case `d2b._resourceCompiler` key one Provider projection lands on.
fn projection_key(owner: &str) -> String {
    let mut key = String::from("providerProjection");
    for segment in owner.split('-') {
        let mut characters = segment.chars();
        if let Some(first) = characters.next() {
            key.extend(first.to_uppercase());
            key.push_str(characters.as_str());
        }
    }
    key
}

/// The kebab-case spelling of one role vocabulary entry.
fn verb_spelling<T: serde::Serialize>(verb: &T) -> String {
    serde_json::to_value(verb)
        .expect("a contract verb serializes")
        .as_str()
        .expect("a contract verb is a string")
        .to_owned()
}

/// The subject vocabulary, projected from the RoleBinding contract.
