//! The broker operation catalog generator.
//!
//! `gen-broker-operations` merges the retained committed operation rows in
//! `docs/reference/policy/broker-operations.json` with the per-crate
//! operation declarations (`operations.json`, one per declaring
//! `d2b-provider-*` crate, KTD3/U2) and writes every derived view of the
//! merged catalog:
//!
//! - `docs/reference/policy/broker-operations.json` - the committed rows
//!   themselves, regenerated as one view of the declarations plus the
//!   retained non-declared rows.
//! - `packages/d2b-contracts-broker/src/generated/broker_operation_profiles.rs`
//!   - the closed Host and Guest profile catalogs.
//! - `packages/d2b-contracts/src/generated/w3_broker_operations.rs` - the
//!   `W3BrokerOperation` inventory.
//! - `packages/d2b-core/src/generated/broker_operation_authz.rs` - the
//!   private broker authorization rows.
//! - `packages/d2b-broker/src/generated/broker_operation_catalog.rs` - the
//!   canonical row table the broker envelope resolves and the completeness
//!   gates compare every view against.
//! - `docs/reference/broker-operation-triage.md` - the human triage view.
//!
//! A row a provider crate declares is the declaration in that crate; every
//! row no crate declares stays committed. A declared operation replaces a
//! committed family row of the same declaring provider (so the migration
//! moves without editing the committed file), appends when it is new, and is
//! refused when the committed file covers it only as a broker-generic row or
//! as another provider's family row. Nothing here restates a facet, so a row
//! cannot move without moving every view, which is what makes the drift gate
//! meaningful.

use std::{
    collections::{BTreeMap, BTreeSet},
    fs,
    path::{Path, PathBuf},
};

use serde::{Deserialize, Serialize};

/// The committed operation rows.
const POLICY_PATH: &str = "docs/reference/policy/broker-operations.json";
/// The generated profile catalog view.
const PROFILES_OUT: &str = "packages/d2b-contracts-broker/src/generated/broker_operation_profiles.rs";
/// The generated `W3BrokerOperation` inventory view.
const W3_OUT: &str = "packages/d2b-contracts/src/generated/w3_broker_operations.rs";
/// The generated private broker authorization row view.
const AUTHZ_OUT: &str = "packages/d2b-core/src/generated/broker_operation_authz.rs";
/// The generated canonical row table.
const CATALOG_OUT: &str = "packages/d2b-broker/src/generated/broker_operation_catalog.rs";
/// The generated triage view.
const TRIAGE_OUT: &str = "docs/reference/broker-operation-triage.md";
/// The directory-glob root the per-crate declarations live under.
const PACKAGES_DIR: &str = "packages";
const PROVIDER_PREFIX: &str = "d2b-provider-";
/// The per-crate operation declaration file (KTD3/U2).
const DECLARATION_FILE: &str = "operations.json";

const HEADER: &str = "@generated by `cargo run -p xtask -- gen-broker-operations`.\n// Do not hand-edit: `//packages/xtask:gen_broker_operations_drift`\n// regenerates this file and compares it byte-for-byte.";

/// One committed broker operation row.
///
/// The field order is the emitted committed-file key order: the generator
/// rewrites `docs/reference/policy/broker-operations.json` from the retained
/// committed rows plus the per-crate declarations, so the emitted bytes must
/// be stable across runs. A facet a row does not carry is omitted rather
/// than emitted as `null`, except the triage trio (`family`,
/// `declaringProvider`, `justification`) and the payload schema, which the
/// historical committed rows spell explicitly.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct Row {
    operation: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    wire_variant: Option<String>,
    owner: String,
    #[serde(default)]
    family: Option<String>,
    #[serde(default)]
    declaring_provider: Option<String>,
    /// Why a row no family owns is not provider-owned.
    ///
    /// A row the broker or a transport concern owns records what owns it and
    /// why, so a non-provider row's triage is a committed fact rather than an
    /// omission; a family-owned row carries its declaring provider instead.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    justification: Option<String>,
    profiles: Vec<String>,
    w3: bool,
    capabilities: bool,
    disposition: String,
    disposition_target: String,
    authz: Authz,
    audit: Audit,
    payload: Payload,
    /// The deadline tier one row sits on (standard unless extended).
    #[serde(default)]
    deadline: Deadline,
    /// The declaring service the operation resolves to, when the row is
    /// family-owned (U7/KD6). The service id is the session-layer address
    /// the declaring provider publishes in its service declaration, and the
    /// method names the declared method that serves this row.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    service: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    method: Option<String>,
    /// The broker-owned state cell the row lives on, when the row declares
    /// one (U3/KTD3).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    state_cell: Option<StateCell>,
    /// The fd-carrying facet of one committed operation row, when the row
    /// declares carriage. A row with no carriage omits the facet, which
    /// admits only the empty leg; a row that declares carriage names the
    /// ceiling and the single kernel kind every attached descriptor must
    /// present.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    fds: Option<Fds>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct Authz {
    subject: String,
    scope: String,
    allowed_groups: Vec<String>,
    destructive: bool,
    secret_access: String,
    broker_required: String,
    audit_mode: String,
}

impl Authz {
    /// The required privilege a declared method carries: the authz
    /// subject/scope pair the authority bound names when it widens (U4).
    pub(crate) fn privilege(&self) -> String {
        format!("{}/{}", self.subject, self.scope)
    }
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct Audit {
    #[serde(default)]
    fields: Vec<String>,
    required: bool,
    mode: String,
    /// The payload fields the row's audit join is derived from.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    join: Vec<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct Payload {
    provenance: String,
    #[serde(default)]
    schema: Option<serde_json::Value>,
}

/// The fd-carrying facet of one committed operation row.
///
/// A row with no carriage declares `maxFds: 0` and no `fdKind`, which
/// admits only the empty leg; a row that declares carriage names the ceiling
/// and the single kernel kind every attached descriptor must present.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct Fds {
    #[serde(default)]
    max_fds: u32,
    #[serde(default)]
    fd_kind: Option<String>,
}

impl Fds {
    /// The descriptor-leg rights ceiling a declared method carries.
    pub(crate) fn max_fds(&self) -> u32 {
        self.max_fds
    }

    /// The descriptor-leg type a declared method carries (U4).
    pub(crate) fn fd_kind(&self) -> Option<&str> {
        self.fd_kind.as_deref()
    }
}

/// The state-cell facet of one committed operation row (U3/KTD3).
///
/// A row with no declared cell leaves both fields absent; a row that names a
/// cell declares the broker-owned state its operation lives on and the
/// cell's durability (one-time records persist under the state root and
/// refuse re-consume across restarts; ephemeral cells reset in-process).
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct StateCell {
    #[serde(default)]
    cell: Option<String>,
    #[serde(default)]
    durability: Option<String>,
}

impl StateCell {
    /// The declared state-cell name one method lives on (U4).
    pub(crate) fn cell(&self) -> Option<&str> {
        self.cell.as_deref()
    }
}

/// The deadline-tier facet of one committed operation row (U4/KTD4).
///
/// A row that declares no tier sits on the standard tier, and every row
/// name outside the closed set fails generation instead of widening what a
/// row may mean.
#[derive(Debug, Default, Clone, Serialize, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub(crate) struct Deadline {
    #[serde(default)]
    tier: Option<String>,
}

/// One provider crate's operation declaration file (KTD3/U2).
///
/// The declaration is the crate's row surface: the facets a crate can state
/// for each operation it serves - operation name, family, declaring
/// provider, payload schema reference, audit facets, fd and state-cell
/// declarations, and the deadline tier - plus the service resolution. The
/// owner is `family` by construction and a declared row never carries a wire
/// variant or a justification: those are broker-side facts, not crate facts.
#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
struct DeclarationFile {
    /// The crate the declaration self-binds to; the file must live in that
    /// crate's directory.
    #[serde(rename = "crate")]
    crate_name: String,
    /// The family operations the crate declares, in declaration order.
    operations: Vec<DeclaredRow>,
}

/// One declared family operation row.
///
/// Every facet a committed family row can carry, minus the facets only the
