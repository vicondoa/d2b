    /// A committed family row of a declaring crate that no declaration
    /// covers, with no wire discriminant, is dropped from the merge: it is a
    /// declaration-generated row whose declaration was deleted, so deleting
    /// an operation needs no edit outside the crate (KTD5).
    #[test]
    fn a_declaration_generated_row_without_a_declaration_is_dropped() {
        let committed = Catalog {
            version: 1,
            rows: vec![
                {
                    let mut row = declared_fixture("GhostOperation", "fixture", "d2b-provider-fixture").into_row();
                    row.operation = "GhostOperation".to_owned();
                    row
                },
                {
                    let mut row = declared_fixture("LiveOperation", "fixture", "d2b-provider-fixture").into_row();
                    row.operation = "LiveOperation".to_owned();
                    row
                },
            ],
        };
        // The declaration covers only LiveOperation; GhostOperation is an
        // orphan of the declaring crate and must not survive.
        let merged = merge_catalog(
            &committed,
            &[(
                "d2b-provider-fixture".to_owned(),
                vec![declared_fixture("LiveOperation", "fixture", "d2b-provider-fixture")],
            )],
        )
        .expect("the merge");
        assert_eq!(merged.rows.len(), 1);
        assert_eq!(merged.rows[0].operation, "LiveOperation");
    }

    /// A retained family row with a wire discriminant survives the orphan
