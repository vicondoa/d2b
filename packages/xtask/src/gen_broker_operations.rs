    /// A declared operation that the committed file already carries as a
    /// committed family row of the same provider replaces it in the merge,
    /// and the emitted catalog keeps every row exactly once.
    #[test]
    fn a_declared_operation_replaces_its_committed_family_row() {
        let committed = committed_catalog();
        let row = committed
            .rows
            .iter()
            .find(|row| row.owner == "family")
            .expect("a family row");
        let operation = row.operation.clone();
        let family = row.family.clone().expect("a family");
        let provider = row
            .declaring_provider
            .clone()
            .expect("a declaring provider");
        let mut declared = declared_fixture(&operation, &family, &provider);
        declared.disposition = "stubbed-unimplemented".to_owned();
        declared.disposition_target = "reserved".to_owned();
        let declarations = vec![("d2b-provider-fixture".to_owned(), vec![declared])];
        let merged = merge_catalog(&committed, &declarations).expect("the migration merge");
        assert_eq!(merged.rows.len(), committed.rows.len());
        let merged_row = merged
            .rows
            .iter()
            .find(|entry| entry.operation == operation)
            .expect("the declared row is present");
        assert_eq!(merged_row.owner, "family");
        assert_eq!(
            merged_row.declaring_provider.as_deref(),
            Some(provider.as_str())
        );
        // The declared facets win over the committed copy.
        assert_eq!(merged_row.disposition, "stubbed-unimplemented");
    }

