//! The Provider crate skeleton and Nix package/catalog generator.
//!
//! `ADR-046-provider-model-and-packaging` work item `ADR046-provider-002`
//! makes the Provider crate layout and the generic Nix Provider
//! package/catalog emitter generated rather than hand-maintained. This module
//! is where that generator lands.
//!
//! What it emits is the frozen shape of a Provider package-catalog entry: the
//! nine field groups the specification's "Package catalog" section enumerates,
//! flattened into the exact field names `nixos-modules/provider-catalog.nix`
//! validates every entry against. The catalog itself is compiled in Nix from
//! `d2b.artifacts.<id>` declarations; only its shape is generated here, so that
//! the module and any later Rust consumer cannot drift apart silently.
//!
//! Three absences in that section are the design rather than gaps, and the
//! generated artifact records them so a later reader does not restore one as a
//! missing feature: selection is by exact digest, so there is no runtime
//! marketplace or download, no PATH or directory discovery, and no `latest` or
//! version-range solving.

use std::{collections::BTreeSet, fs, path::Path, path::PathBuf};

const GENERATED_HEADER: &str = concat!(
    "# Generated by `cargo run --manifest-path packages/Cargo.toml -p xtask -- \\\n",
    "#   gen-provider-packaging`. Do not hand-edit: the drift gate compares this\n",
    "# file byte-for-byte against the generator output.\n",
);

/// One field group of a catalog entry, as the specification enumerates them.
struct FieldGroup {
    /// The specification's own bullet text, reproduced as the group comment.
    bullet: &'static str,
    /// The entry fields the bullet names, in the bullet's own order.
    fields: &'static [&'static str],
}

/// The nine field groups of the "Package catalog" section, in its order.
///
/// The order is the specification's and is not a preference: a reader
/// comparing the artifact against the section should be able to walk both top
/// to bottom. The flattened, sorted field list is emitted alongside it, because
/// that is the form a validator wants.
const CATALOG_FIELD_GROUPS: &[FieldGroup] = &[
    FieldGroup {
        bullet: "Provider/package/publisher/version",
        fields: &["providerName", "packageName", "publisher", "version"],
    },
    FieldGroup {
        bullet: "package/executable/manifest/component/descriptor/config digests",
        fields: &[
            "packageDigest",
            "executableDigest",
            "manifestDigest",
            "componentDigest",
            "descriptorDigest",
            "configDigest",
        ],
    },
    FieldGroup {
        bullet: "systems/platform",
        fields: &["systems", "platform"],
    },
    FieldGroup {
        bullet: "API/service compatibility",
        fields: &["apiCompatibility", "serviceCompatibility"],
    },
    FieldGroup {
        bullet: "signature/root epoch/revocation/deny status",
        fields: &["signature", "rootEpoch", "revocationStatus", "denyStatus"],
    },
    FieldGroup {
        bullet: "provenance/SBOM/license/vulnerability evidence",
        fields: &[
            "provenanceEvidence",
            "sbomEvidence",
            "licenseEvidence",
            "vulnerabilityEvidence",
        ],
    },
    FieldGroup {
        bullet: "conformance attestation",
        fields: &["conformanceAttestation"],
    },
    FieldGroup {
        bullet: "support channel",
        fields: &["supportChannel"],
    },
    FieldGroup {
        bullet: "support contact",
        fields: &["supportContact"],
    },
];

/// The subset of entry fields that carry a digest and are therefore the fields
/// exact-digest selection compares. Named separately so the module can require
/// them present and non-empty without re-deriving the set from a name suffix.
const DIGEST_FIELDS: &[&str] = &[
    "componentDigest",
    "configDigest",
    "descriptorDigest",
    "executableDigest",
    "manifestDigest",
    "packageDigest",
];

/// The mechanisms the specification rules out. Emitted so the module can name
/// the rule it is enforcing when it refuses an entry.
const EXCLUDED_MECHANISMS: &[&str] = &[
    "directory-discovery",
    "latest",
    "path-scan",
    "runtime-download",
    "runtime-marketplace",
    "version-range-solving",
];

fn nix_string(value: &str) -> String {
    let mut escaped = String::with_capacity(value.len() + 2);
    escaped.push('"');
    for character in value.chars() {
        match character {
            '"' => escaped.push_str("\\\""),
            '\\' => escaped.push_str("\\\\"),
            '\n' => escaped.push_str("\\n"),
            '$' => escaped.push_str("\\$"),
            other => escaped.push(other),
        }
    }
    escaped.push('"');
    escaped
}

fn nix_string_list(values: impl IntoIterator<Item = String>, indent: usize) -> String {
    let pad = " ".repeat(indent);
    let inner = " ".repeat(indent + 2);
    let mut out = String::from("[\n");
    for value in values {
        out.push_str(&format!("{inner}{}\n", nix_string(&value)));
    }
    out.push_str(&format!("{pad}]"));
    out
}

/// Every catalog entry field, flattened and sorted.
fn all_fields() -> Vec<String> {
    let unique: BTreeSet<String> = CATALOG_FIELD_GROUPS
        .iter()
        .flat_map(|group| group.fields.iter().map(|field| (*field).to_owned()))
        .collect();
    unique.into_iter().collect()
}

/// Render the generated catalog-shape module.
fn generated_catalog_shape_module() -> String {
    let mut out = String::new();
    out.push_str(GENERATED_HEADER);
    out.push_str(
        "#\n\
         # The frozen shape of one entry in the offline Provider package\n\
         # catalog, from the \"Package catalog\" section of\n\
         # docs/specs/ADR-046-provider-model-and-packaging.md.\n\
         #\n\
         # Selection is by exact digest. The excluded mechanisms below are\n\
         # ruled out by that section and are absent by design, not by\n\
         # omission.\n",
    );
    out.push_str("{\n");

    out.push_str("  # Entry field groups, in the specification's own order.\n");
    out.push_str("  fieldGroups = [\n");
    for group in CATALOG_FIELD_GROUPS {
        out.push_str("    {\n");
        out.push_str(&format!("      bullet = {};\n", nix_string(group.bullet)));
        out.push_str(&format!(
            "      fields = {};\n",
            nix_string_list(group.fields.iter().map(|field| (*field).to_owned()), 6)
        ));
        out.push_str("    }\n");
    }
    out.push_str("  ];\n\n");

    out.push_str("  # Every entry field, flattened and sorted. A catalog entry\n");
    out.push_str("  # carries exactly these attributes.\n");
    out.push_str(&format!(
        "  fields = {};\n\n",
        nix_string_list(all_fields(), 2)
    ));

    out.push_str("  # The fields exact-digest selection compares.\n");
    out.push_str(&format!(
        "  digestFields = {};\n\n",
        nix_string_list(DIGEST_FIELDS.iter().map(|field| (*field).to_owned()), 2)
    ));

    out.push_str("  # Ruled out by the specification; recorded so a reader does\n");
    out.push_str("  # not restore one as a missing feature.\n");
    out.push_str(&format!(
        "  excludedMechanisms = {};\n",
        nix_string_list(
            EXCLUDED_MECHANISMS.iter().map(|value| (*value).to_owned()),
            2
        )
    ));

    out.push_str("}\n");
    out
}

/// Generate the Provider crate skeletons and the Nix Provider
/// package/catalog artifacts.
///
/// Returns the paths written. An empty success is deliberately not a possible
/// return: a caller comparing a generator's output against the committed tree
/// must not be able to read "wrote nothing" as "everything is current".
pub fn gen_provider_packaging(
    repo_root: &Path,
) -> Result<Vec<PathBuf>, Box<dyn std::error::Error>> {
    let out_dir = repo_root.join("nixos-modules/generated");
    fs::create_dir_all(&out_dir)?;

    let path = out_dir.join("provider-catalog-shape.nix");
    fs::write(&path, generated_catalog_shape_module())?;

    let written = vec![path];
    if written.is_empty() {
        return Err("gen-provider-packaging wrote no artifact; refusing to report success".into());
    }
    Ok(written)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_specification_bullet_has_at_least_one_field() {
        assert_eq!(
            CATALOG_FIELD_GROUPS.len(),
            9,
            "the Package catalog section enumerates nine bullets"
        );
        for group in CATALOG_FIELD_GROUPS {
            assert!(
                !group.fields.is_empty(),
                "bullet '{}' names no field",
                group.bullet
            );
        }
    }

    #[test]
    fn no_field_is_declared_by_two_groups() {
        let mut seen = BTreeSet::new();
        for group in CATALOG_FIELD_GROUPS {
            for field in group.fields {
                assert!(
                    seen.insert(*field),
                    "field '{field}' is declared by more than one group"
                );
            }
        }
        assert_eq!(seen.len(), all_fields().len());
    }

    #[test]
    fn the_digest_fields_are_a_sorted_subset_of_the_entry_fields() {
        let fields = all_fields();
        let mut sorted = DIGEST_FIELDS.to_vec();
        sorted.sort_unstable();
        assert_eq!(DIGEST_FIELDS, sorted.as_slice(), "digest fields are sorted");
        for digest in DIGEST_FIELDS {
            assert!(
                fields.iter().any(|field| field == digest),
                "digest field '{digest}' is not an entry field"
            );
        }
    }

    #[test]
    fn the_excluded_mechanisms_are_sorted_and_unique() {
        let mut sorted = EXCLUDED_MECHANISMS.to_vec();
        sorted.sort_unstable();
        sorted.dedup();
        assert_eq!(EXCLUDED_MECHANISMS, sorted.as_slice());
    }

    #[test]
    fn the_rendered_module_is_byte_identical_across_repeated_renders() {
        let first = generated_catalog_shape_module();
        for _ in 0..8 {
            assert_eq!(first, generated_catalog_shape_module());
        }
    }

    #[test]
    fn the_rendered_module_contains_no_non_ascii_dash() {
        let banned = [
            '\u{2010}', '\u{2011}', '\u{2012}', '\u{2013}', '\u{2014}', '\u{2015}', '\u{2212}',
            '\u{fe58}', '\u{ff0d}',
        ];
        let rendered = generated_catalog_shape_module();
        for character in banned {
            assert!(
                !rendered.contains(character),
                "generated artifact must not contain U+{:04X}",
                character as u32
            );
        }
    }

    #[test]
    fn the_generator_never_reports_an_empty_success() {
        // The contract the stub established and this implementation keeps: a
        // successful return names at least one written path, so a drift gate
        // cannot read silence as currency.
        let dir =
            std::env::temp_dir().join(format!("d2b-provider-packaging-gen-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        let written = gen_provider_packaging(&dir).expect("generation succeeds");
        assert!(!written.is_empty());
        for path in &written {
            assert!(path.is_file(), "{} was not written", path.display());
        }
        let _ = fs::remove_dir_all(&dir);
    }
}
