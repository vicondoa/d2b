//! Shared authority scaffolding: the provider-crate enumeration and the
//! per-crate declaration coverage gate every declaration authority reads
//! through, the recursive `.rs` collector, and the committed-artifact drift
//! check. One home instead of four byte-identical private copies.
//!
//! The coverage gate exists because an absent declaration file and a renamed
//! one look the same on disk. A loader that skips what it cannot find turns a
//! rename into a smaller registry: the generated type authority, the committed
//! Nix registry, and the new-graph projection all shrink together, and every
//! gate compares the generated bytes against the same shrunken input, so the
//! suite stays green over a silent loss. [`declaration_paths`] therefore
//! refuses a provider crate that carries no file for a declaration kind unless
//! [`DECLARATION_ABSENCES`] names it and states why it owns no such surface.

use std::{
    fs,
    path::{Path, PathBuf},
};

/// The directory the per-crate declarations live under.
const PACKAGES_DIR: &str = "packages";
/// The directory-name prefix that marks a package as a provider crate.
const PROVIDER_PREFIX: &str = "d2b-provider-";

/// One per-crate declaration file a provider crate may carry.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub(crate) enum Declaration {
    /// The ResourceType and role vocabulary a crate registers.
    ResourceTypes,
    /// The broker operation rows a crate owns.
    Operations,
    /// The provider identity and effect-service ids a crate registers.
    Registrations,
    /// The Provider identities a crate owns, one slot per identity surface.
    ProviderIdentity,
    /// The service packages a crate publishes.
    ServiceCatalog,
}

impl Declaration {
    /// Every declaration kind, in the order the coverage gate reads them.
    ///
    /// Each authority names the one kind it loads by name, so the closed
    /// enumeration is read by the coverage-gate tests: they stage a crate
    /// that carries every kind and refuse it one kind at a time, which is
    /// what keeps a kind from escaping the gate by never being exercised.
    #[cfg(test)]
    pub(crate) const ALL: [Self; 5] = [
        Self::ResourceTypes,
        Self::Operations,
        Self::Registrations,
        Self::ProviderIdentity,
        Self::ServiceCatalog,
    ];

    /// The file name, exactly as it sits in the crate's own directory.
    pub(crate) const fn file_name(self) -> &'static str {
        match self {
            Self::ResourceTypes => "resource-types.json",
            Self::Operations => "operations.json",
            Self::Registrations => "registrations.json",
            Self::ProviderIdentity => "provider-identity.json",
            Self::ServiceCatalog => "service-catalog.json",
        }
    }
}

/// Whether one declared Provider identity is a name the contracts admit as
/// a resource name.
///
/// A declaration states the identity its own crate registers, and the
/// crate's directory name is not that identity: `d2b-provider-guest-qemu-media`
/// registers `runtime-qemu-media` and `d2b-provider-process-minijail`
/// registers `system-minijail`. A convention that read the identity back out
/// of the directory name therefore both published references the product
/// does not have and refused the ones it does, which made a crate's real
/// identity inexpressible. What a declaration owes is the grammar, not the
/// spelling of the directory beside it, so this is the whole of what both
/// declaration authorities gate: an identity the resource-name grammar
/// refuses could never be written as a `Provider/<name>` reference, so a
/// declaration naming one states a row no production surface could carry.
pub(crate) fn admits_provider_identity(identity: &str) -> bool {
    d2b_contracts_resource::v3::ResourceName::parse(identity).is_ok()
}

/// One provider crate that deliberately carries no file for `absent`, and
/// why.
///
/// A crate owns the plane-facing surfaces it declares and no others: the crate
/// that registers a ResourceType vocabulary declares it, the crate that owns an
/// operation declares its row, and the crate that publishes a service package
/// declares it in its catalog. A crate that owns no surface of a kind has no
/// file for it, and that has to be written down. The gate refuses a crate that
/// carries none without a row, so every deliberate absence is a reviewable
/// line here rather than a branch in a loader.
///
/// The rows are one per crate and the table only ever needs to grow when a new
/// provider crate appears; a crate that gains a declaration is read normally
/// and its row simply stops naming that kind.
struct DeclarationAbsence {
    /// The provider crate that owns no file for `absent`.
    crate_name: &'static str,
    /// The declaration kinds it declares nothing of.
    absent: &'static [Declaration],
    /// Why the crate owns no surface of those kinds.
    reason: &'static str,
}

