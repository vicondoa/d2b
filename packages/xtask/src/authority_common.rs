/// The provider crates in the tree, each paired with its own directory, in
/// crate-name order.
///
/// This is the one enumeration every declaration authority reads through, so
/// the set of crates the loaders consider is stated once rather than
/// re-derived - and restated - by each of them.
#[allow(clippy::disallowed_methods, reason = "CLI-only path")]
pub(crate) fn provider_crates(repo_root: &Path) -> Result<Vec<(String, PathBuf)>, String> {
    let packages_dir = repo_root.join(PACKAGES_DIR);
    let entries = fs::read_dir(&packages_dir)
        .map_err(|error| format!("cannot read {}: {error}", packages_dir.display()))?;
    let mut crates = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|error| format!("cannot read a packages entry: {error}"))?;
        let crate_name = entry.file_name().to_string_lossy().into_owned();
        if crate_name.starts_with(PROVIDER_PREFIX) {
            crates.push((crate_name, entry.path()));
        }
    }
    crates.sort();
    Ok(crates)
}

/// The provider crates that carry `declaration`, each paired with its path, in
/// crate-name order.
///
/// Every provider crate the enumeration reaches either appears in this list or
/// has a [`DECLARATION_ABSENCES`] row naming the kinds it owns no file for. A
/// crate that carries none without such a row is refused by name, and the
/// refusal lists every such crate at once, so a renamed declaration file fails
/// the render instead of quietly removing its family from it.
///
/// The rows are not themselves checked against the tree here: the same
/// enumeration runs over partial trees - a test fixture, or the sandbox a
/// generator's drift target stages - where a listed crate may legitimately
/// carry a file its row does not name. The tree-level truth of the table is
/// asserted over the repository instead.
#[allow(clippy::disallowed_methods, reason = "CLI-only path")]
pub(crate) fn declaration_paths(
    repo_root: &Path,
    declaration: Declaration,
) -> Result<Vec<(String, PathBuf)>, String> {
    let mut carried = Vec::new();
    let mut missing = Vec::new();
    for (crate_name, crate_dir) in provider_crates(repo_root)? {
        let path = crate_dir.join(declaration.file_name());
        let recorded = DECLARATION_ABSENCES.iter().find(|row| row.crate_name == crate_name);
        if path.is_file() {
            carried.push((crate_name, path));
        } else if !recorded.is_some_and(|row| row.absent.contains(&declaration)) {
            // A row naming this kind as one the crate owns none of is the
            // only absence the table may state; anything else is a lost file.
            missing.push(missing_declaration(&crate_name, declaration, recorded));
        }
    }
    if !missing.is_empty() {
        return Err(missing.join("\n"));
    }
    Ok(carried)
}

/// The refusal for one crate whose declaration file is missing, carrying the
/// row that already exists for it when it has one: whoever hits this is
/// repairing a declaration that used to be there, and the recorded reason is
/// what tells them which side of the line the crate is on.
